const PHONE_INTERVIEW_MAP: Record<string, PhoneInterviewDetail> = {
  [INTERVIEW_OXXX.slug]: INTERVIEW_OXXX,
};

export function getPhoneInterviewList(): PhoneInterviewListItem[] {
  return Object.values(PHONE_INTERVIEW_MAP).map((item) => ({
    slug: item.slug,
    title: item.title,
    companyName: item.companyName,
    image: item.image,
  }));
}

export function getPhoneInterviewBySlug(
  slug: string
): PhoneInterviewDetail | null {
  return PHONE_INTERVIEW_MAP[slug] ?? null;
}

export function getPhoneInterviewSlugs(): string[] {
  return Object.keys(PHONE_INTERVIEW_MAP);
}
